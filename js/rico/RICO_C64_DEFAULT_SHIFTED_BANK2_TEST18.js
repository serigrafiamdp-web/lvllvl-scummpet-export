(function() {
  'use strict';

  if(typeof TileSet === 'undefined') {
    console.error('[RICO TEST18] TileSet not found.');
    return;
  }

  var BANK2_FIELD = 'ricoCharsetBank2';
  var BANK_SIZE = 256;
  var SHIFTED_PRESET = 'petscii_shifted';
  var TILE_W = 8;
  var TILE_H = 8;
  var initSerial = 0;
  var pendingByTileSet = [];

  function cloneProps(props) {
    var out = {};
    props = props || {};
    for(var key in props) {
      if(props.hasOwnProperty(key)) out[key] = props[key];
    }
    return out;
  }

  function hasBank2(tileSet) {
    var record = null;
    try { record = tileSet && tileSet.getDocRecord ? tileSet.getDocRecord() : null; } catch(e) {}
    var stored = record && record.data ? record.data[BANK2_FIELD] : null;
    return !!(stored && stored.version === 1 && stored.tileData && stored.tileData.length >= BANK_SIZE);
  }

  function isNormalC64(tileSet) {
    if(!tileSet) return false;

    // TEST07 records the selected preset on the TileSet. The stock startup C64
    // can also report itself as PETSCII before preset metadata is present.
    if(tileSet.preset === 'petscii') return true;
    if(tileSet.preset && tileSet.preset !== 'petscii') return false;

    try {
      if(typeof tileSet.isPetscii === 'function' && tileSet.isPetscii()) return true;
    } catch(e) {}

    return tileSet.type === 'petscii' && tileSet.getTileCount && tileSet.getTileCount() === BANK_SIZE;
  }

  function tileSetKey(tileSet) {
    try {
      if(tileSet && typeof tileSet.getId === 'function') return String(tileSet.getId());
    } catch(e) {}
    return String(tileSet && tileSet.tileSetId ? tileSet.tileSetId : 'current');
  }

  function markPending(tileSet, value) {
    var key = tileSetKey(tileSet);
    for(var i = 0; i < pendingByTileSet.length; i++) {
      if(pendingByTileSet[i].key === key) {
        pendingByTileSet[i].value = value;
        return;
      }
    }
    pendingByTileSet.push({ key: key, value: value });
  }

  function isPending(tileSet) {
    var key = tileSetKey(tileSet);
    for(var i = 0; i < pendingByTileSet.length; i++) {
      if(pendingByTileSet[i].key === key) return pendingByTileSet[i].value === true;
    }
    return false;
  }

  function imageToBankSnapshot(tileSet, img) {
    var temp = document.createElement('canvas');
    temp.width = img.naturalWidth;
    temp.height = img.naturalHeight;
    var ctx = temp.getContext('2d');
    ctx.clearRect(0, 0, temp.width, temp.height);
    ctx.drawImage(img, 0, 0);
    var imageData = ctx.getImageData(0, 0, temp.width, temp.height);

    var across = Math.floor(img.naturalWidth / TILE_W);
    var down = Math.floor(img.naturalHeight / TILE_H);
    var count = across * down;
    if(count < BANK_SIZE) return null;

    var snapshot = [];
    for(var tile = 0; tile < BANK_SIZE; tile++) {
      var col = tile % across;
      var row = Math.floor(tile / across);
      var pixels = [];

      for(var y = 0; y < TILE_H; y++) {
        for(var x = 0; x < TILE_W; x++) {
          var sx = col * TILE_W + x;
          var sy = row * TILE_H + y;
          var pos = (sx + sy * imageData.width) * 4;
          pixels.push(imageData.data[pos] > 100 ? 1 : 0);
        }
      }

      var source = tileSet.tileData && tileSet.tileData[tile] ? tileSet.tileData[tile] : null;
      snapshot.push({
        data: [pixels],
        props: cloneProps(source ? source.props : null)
      });
    }
    return snapshot;
  }

  function redrawSidePalette() {
    try {
      var editor = g_app && g_app.textModeEditor;
      if(editor && editor.sideTilePalette && typeof editor.sideTilePalette.drawTilePalette === 'function') {
        editor.sideTilePalette.drawTilePalette({ redrawTiles: true });
      }
    } catch(e) {
      console.error('[RICO TEST18] Side palette redraw failed.', e);
    }
  }

  function createDefaultShiftedBank2(tileSet, forceForC64Preset) {
    if(!tileSet || !tileSet.getTileCount || tileSet.getTileCount() !== BANK_SIZE) return false;
    if(hasBank2(tileSet)) return true;
    if(!forceForC64Preset && !isNormalC64(tileSet)) return false;
    if(isPending(tileSet)) return false;

    markPending(tileSet, true);
    var serial = ++initSerial;
    var img = new Image();

    img.onload = function() {
      markPending(tileSet, false);
      if(hasBank2(tileSet)) return;

      var snapshot = imageToBankSnapshot(tileSet, img);
      if(!snapshot) {
        console.error('[RICO TEST18] Shifted source did not contain 256 glyphs.');
        return;
      }

      var record = null;
      try { record = tileSet.getDocRecord(); } catch(e) {}
      if(!record || !record.data) {
        console.error('[RICO TEST18] Could not access TileSet document record.');
        return;
      }

      record.data[BANK2_FIELD] = {
        version: 1,
        width: tileSet.getTileWidth ? tileSet.getTileWidth() : TILE_W,
        height: tileSet.getTileHeight ? tileSet.getTileHeight() : TILE_H,
        tileData: snapshot,
        autoGenerated: true,
        defaultSource: SHIFTED_PRESET
      };

      if(typeof tileSet.modified === 'function') tileSet.modified();
      redrawSidePalette();
      console.log('[RICO TEST18] Default C64 BANK 2 initialised from C64 Shifted (256 glyphs).');
    };

    img.onerror = function() {
      markPending(tileSet, false);
      console.error('[RICO TEST18] Could not load charsets/' + SHIFTED_PRESET + '.png (request ' + serial + ').');
    };

    img.src = 'charsets/' + SHIFTED_PRESET + '.png?ricoDefaultBank2=' + serial;
    return false;
  }

  // If the user applies the normal C64 preset later, ensure its companion BANK 2
  // defaults to the shifted C64 charset. Existing/custom BANK 2 data is preserved.
  var previousSetToPreset = TileSet.prototype.setToPreset;
  TileSet.prototype.setToPreset = function(preset, callback) {
    var rawPreset = preset;
    var mode = 'textmode';
    var id = rawPreset;
    var pos = rawPreset.indexOf(':');
    if(pos !== -1) {
      mode = rawPreset.substring(0, pos);
      id = rawPreset.substring(pos + 1);
    }

    var self = this;
    var wrapped = callback;
    if(mode !== 'vector' && id === 'petscii') {
      wrapped = function() {
        createDefaultShiftedBank2(self, true);
        if(callback) callback();
      };
    }

    var result = previousSetToPreset.call(this, preset, wrapped);

    // Some loader paths can complete synchronously or omit callback usage.
    if(mode !== 'vector' && id === 'petscii') {
      setTimeout(function() { createDefaultShiftedBank2(self, true); }, 0);
    }
    return result;
  };

  // Startup/new-project path: wait until the active C64 tileset exists, then seed
  // BANK 2 once. Never overwrite a BANK 2 that already exists (e.g. Rico Remix).
  UI.on('ready', function() {
    var tries = 0;
    var timer = setInterval(function() {
      tries++;
      try {
        var editor = g_app && g_app.textModeEditor;
        var tileSet = editor && editor.tileSetManager && editor.tileSetManager.getCurrentTileSet
          ? editor.tileSetManager.getCurrentTileSet() : null;
        if(tileSet && (hasBank2(tileSet) || createDefaultShiftedBank2(tileSet, false))) {
          clearInterval(timer);
        }
      } catch(e) {}
      if(tries >= 160) clearInterval(timer);
    }, 50);
  });

  window.RICO_TEST18_DEFAULT_SHIFTED_BANK2 = true;
  console.log('[RICO TEST18] Default C64 normal + shifted BANK 2 hook loaded.');
})();